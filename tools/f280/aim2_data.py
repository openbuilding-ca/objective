#!/usr/bin/env python3
"""Write src/core/Aim2Data.js: the tables AIM2.xls (CSA F280-12 Cl. 5.2.3) selects its inputs from.

    python3 tools/f280/aim2_data.py <AIM2.xlsx> > src/core/Aim2Data.js

F280-12 Cl. 5.2.3: the air-leakage rate for heating, LRairh, is "the output from the spreadsheet"
AIM2.xls (NRCan's implementation of AIM-2, Walker & Wilson 1990, as HOT2000 uses it). Its
calculations sit in the AIM_2_Calcs tab (src/core/Aim2.js ports them); its choices are tables in
AIM_2_Selection and AIM_2_Leak_Distrib, copied here as stored. Open AIM2.xls in Excel (read-only:
it carries ActiveX controls) and save it as .xlsx first. Weather (January / July wind) comes from
F280's own table: src/core/F280Weather.js (AIM_2_Weather is the same table).

  terrain        AIM_2_Selection C303:D310 - the 8 terrain classes and their roughness length z0 (m),
                 used for the weather station (Z_met, B301) and the building site (Z_site, B315)
  shielding      C322:D326 - the 5 local-shielding classes and their wind shelter coefficient, for the
                 walls (Sw_o, B320) and the flue (Sw_flue, B330)
  buildingType / storeys / foundation   C340:D341, C347:D351, C357:D360 - their codes
  leakage        AIM_2_Leak_Distrib H3:K43 - ceiling / walls / floor leakage fractions by the code
                 type x storeys x foundation (B365's CONCATENATE)
  tightness      AIM_2_Calcs A12:D15 - the prescribed air-tightness types: ACH @ 50 Pa, Cnorm, n
                 (their ELA @ 10 Pa = Con2 x Cnorm x volume x 10^(n - 0.5), AIM_2_Calcs E12:E15)
"""

import json
import sys

import openpyxl


def column(ws, rng):
    return [[c.value for c in row] for row in ws[rng]]


def main(path):
    wb = openpyxl.load_workbook(path, data_only=True)
    sel, leak, calcs = wb["AIM_2_Selection"], wb["AIM_2_Leak_Distrib"], wb["AIM_2_Calcs"]
    terrain = [{"name": n, "z0": z} for n, z in column(sel, "C303:D310")]
    shielding = [{"name": n, "sw": v} for n, v in column(sel, "C322:D326")]
    building_type = {n: v for n, v in column(sel, "C340:D341")}
    storeys = {n: v for n, v in column(sel, "C347:D351")}
    foundation = {n: v for n, v in column(sel, "C357:D360")}
    leakage = {}
    for code, ceiling, walls, floor in column(leak, "H4:K43"):
        if abs(ceiling + walls + floor - 1) > 1e-12:
            raise SystemExit(f"{path}: leakage {code} does not sum to 1")
        leakage[str(code)] = {"ceiling": ceiling, "walls": walls, "floor": floor}
    tightness = [{"name": n, "ach50": a, "cnorm": c, "n": k} for n, a, c, k in column(calcs, "A12:D15")]
    for t in terrain + shielding:
        if None in t.values():
            raise SystemExit(f"{path}: an empty cell in {t}")
    if len(leakage) != 40:
        raise SystemExit(f"{path}: {len(leakage)} leakage rows, not 2 x 5 x 4")
    data = {"terrain": terrain, "shielding": shielding, "buildingType": building_type, "storeys": storeys,
            "foundation": foundation, "leakage": leakage, "tightness": tightness}
    print("/**")
    print(" * Aim2Data.js - GENERATED by tools/f280/aim2_data.py from AIM2.xls; never edit by hand.")
    print(" * The tables AIM2.xls (CSA F280-12 Cl. 5.2.3) chooses its inputs from. The method: src/core/Aim2.js.")
    print(" */")
    print("(function () {")
    print("  window.TEUI = window.TEUI || {};")
    print("  window.TEUI.Aim2Data = Object.freeze(%s);" % json.dumps(data, separators=(",", ":")))
    print("})();")


if __name__ == "__main__":
    if len(sys.argv) != 2:
        raise SystemExit(__doc__)
    main(sys.argv[1])
