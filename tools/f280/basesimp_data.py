#!/usr/bin/env python3
"""Write src/core/BasesimpData.js: BASESIMP's correlation coefficients and corner-correction table.

    python3 tools/f280/basesimp_data.py <FoundationCC.xlsx> <BasementHLR_2014.xlsx> <BSMCFG_English_2015.TXT> \
        > src/core/BasesimpData.js

CSA F280-12 Cl. 5.2.2.1 requires the spreadsheet BasementHLR.xls for every foundation element in contact
with soil; its configuration number d) is "as found in the spreadsheet, FoundationCC.xls", and BSMCFG.TXT
"contains word descriptions of the 145 configurations". The three files ship in F280_Package (NRCan, Brian
Bradley 2012: "essentially publically available in conference papers"; Andy's copy:
iCloud [T] Active Projects/2022 | Open Building/00 CERTIFICATIONS/CSA_F280-12/F280_Package).

The .xls files are Excel 97-2004; open each in Excel and save it as .xlsx first (openpyxl reads .xlsx only).
Every value is copied as stored - no rounding, no edits:
  * FoundationCC.xlsx, sheet CorrCoef, rows 4-148: '#', 'Name', then the 49 values that BasementHLR's
    CORC tab holds (pasted transposed there, BasementHLR.doc): a1..j1 (SUMUO), q2..h2 (SUMUR), a3..i3
    (ATTEN), a4..cc4 (PHASE), CCF (corner-correction column), iUnInsul (the uninsulated twin BS2 uses),
    WalkSlab, iFndFlag1..8.
  * BasementHLR_2014.xlsx, sheet CornerCF, B2:T17: the corner-correction coefficients (Beausoleil-Morrison
    et al 1995b), 8 columns x (steady, variable): row iuse = 2*(icol-1)+1 (steady) and +2 (variable).
"""

import json
import re
import sys

import openpyxl

NAMES = (
    "a1 b1 cc1 d1 e1 f1 g1 h1 i1 j1 "
    "q2 rr2 u2 v2 w2 x2 s2 t2 y2 a2 b2 cc2 d2 e2 f2 g2 h2 "
    "a3 b3 cc3 e3 f3 g3 h3 i3 "
    "a4 b4 cc4 CCF iUnInsul WalkSlab "
    "iFndFlag1 iFndFlag2 iFndFlag3 iFndFlag4 iFndFlag5 iFndFlag6 iFndFlag7 iFndFlag8"
).split()
assert len(NAMES) == 49


def configs(path):
    ws = openpyxl.load_workbook(path, data_only=True)["CorrCoef"]
    header = [c.value for c in ws[3]]
    if header[:4] != ["#", "Name", "a1", "b1"]:
        raise SystemExit(f"{path}: CorrCoef row 3 is not the header I expect: {header[:6]}")
    out = {}
    for row in ws.iter_rows(min_row=4, values_only=True):
        if row[0] is None:
            continue
        n, name, vals = int(row[0]), str(row[1]).strip(), list(row[2:51])
        if any(v is None for v in vals):
            raise SystemExit(f"{path}: configuration {n} {name} has an empty coefficient")
        out[n] = {"name": name, **dict(zip(NAMES, vals))}
    return out


def corner(path):
    ws = openpyxl.load_workbook(path, data_only=True)["CornerCF"]
    rows = []
    for i, r in enumerate(ws.iter_rows(min_row=2, max_row=17, min_col=1, max_col=20, values_only=True)):
        if r[0] != i + 1 or any(v is None for v in r):
            raise SystemExit(f"{path}: CornerCF row {i + 2} is not row index {i + 1} with 19 coefficients: {r}")
        rows.append(list(r[1:]))
    return rows


def descriptions(path):
    text = open(path, encoding="latin-1").read()
    out = {}
    blocks = re.split(r"\n\s*Configuration:\s*#\s*", text)
    for b in blocks[1:]:
        m = re.match(r"(\d+)\s*=\s*(\S+)\s+\d+\s*\n(.*)", b, re.S)
        if not m:
            continue
        lines = []
        for ln in m.group(3).splitlines():
            ln = ln.strip()
            if not ln:
                break
            if ln.startswith("- "):
                lines.append(ln[2:])
            elif lines:
                lines[-1] += " " + ln
        out[int(m.group(1))] = {"name": m.group(2), "lines": lines}
    return out


def main(cc_path, hlr_path, cfg_path):
    cfg = configs(cc_path)
    desc = descriptions(cfg_path)
    for n, d in desc.items():
        if n in cfg and cfg[n]["name"] != d["name"]:
            raise SystemExit(f"configuration {n}: FoundationCC says {cfg[n]['name']}, BSMCFG says {d['name']}")
        if n in cfg:
            cfg[n]["description"] = d["lines"]
    data = {"configs": cfg, "cornerCF": corner(hlr_path)}
    print("/**")
    print(" * BasesimpData.js - GENERATED by tools/f280/basesimp_data.py; never edit by hand.")
    print(" *")
    print(" * BASESIMP's correlation coefficients (FoundationCC.xls, %d configurations) and the" % len(cfg))
    print(" * corner-correction table (BasementHLR.xls, CornerCF), as CSA F280-12 Cl. 5.2.2.1 requires.")
    print(" * Descriptions from BSMCFG_English_2015.TXT. The method: src/core/Basesimp.js.")
    print(" */")
    print("(function () {")
    print("  window.TEUI = window.TEUI || {};")
    print("  window.TEUI.BasesimpData = Object.freeze(%s);" % json.dumps(data, indent=None, separators=(",", ":")))
    print("})();")


if __name__ == "__main__":
    if len(sys.argv) != 4:
        raise SystemExit(__doc__)
    main(*sys.argv[1:])
